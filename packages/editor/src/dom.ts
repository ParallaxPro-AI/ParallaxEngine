/**
 * The editor builds its DOM procedurally (no framework): `h()` makes an element with a
 * class, attributes and children; panels are classes owning one root element.
 */

type Child = Node | string | null | undefined | false;

export interface Attributes {
  readonly [name: string]: string | number | boolean | undefined | ((event: Event) => void);
}

/** `h('div.panel.left', { title: 'x', onclick: fn }, child, 'text')`. */
export function h<K extends keyof HTMLElementTagNameMap>(tag: K | `${K}.${string}`, attrs: Attributes = {}, ...children: Child[]): HTMLElementTagNameMap[K] {
  const [name, ...classes] = tag.split('.') as [K, ...string[]];
  const el = document.createElement(name);
  if (classes.length > 0) el.className = classes.join(' ');
  for (const [key, value] of Object.entries(attrs)) {
    if (value === undefined || value === false) continue;
    if (typeof value === 'function') el.addEventListener(key.replace(/^on/, ''), value as EventListener);
    else if (key === 'text') el.textContent = String(value);
    else el.setAttribute(key, value === true ? '' : String(value));
  }
  for (const child of children) if (child !== null && child !== undefined && child !== false) el.append(child);
  return el;
}

/** Remove every child. */
export function clear(el: Element): void {
  while (el.firstChild !== null) el.firstChild.remove();
}

/** A panel's header row and scrolling body, as the editor's panels share them. */
export function panelFrame(title: string, ...actions: Node[]): { root: HTMLElement; header: HTMLElement; body: HTMLElement } {
  const header = h('div.panel-header', {}, h('span.panel-title', { text: title }), h('span.panel-actions', {}, ...actions));
  const body = h('div.panel-body');
  return { root: h('section.panel', {}, header, body), header, body };
}

