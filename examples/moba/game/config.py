"""Match-wide tunables: config/match.json, read with `ctx.config(MatchRules)`."""

from parallax import Localized, config, field

from game.content import WaveMix


@config("match")
class MatchRules:
    draft_seconds: float = field(unit="s")
    start_gold: int = field()
    gold_per_second: int = field()
    xp_per_second: float = field()
    xp_base: float = field(doc="XP to level up = xp_base + xp_per_level × level.")
    xp_per_level: float = field()
    max_level: int = field()
    basic_rank_levels: list[int] = field(doc="Levels at which each rank of Q/W/E unlocks.")
    ultimate_rank_levels: list[int] = field(doc="Levels at which each rank of R unlocks.")
    item_slots: int = field()
    recall_seconds: float = field(unit="s")
    first_wave: float = field(unit="s")
    wave_interval: float = field(unit="s")
    wave_mix: list[WaveMix] = field()
    health_growth: float = field(doc="Per wave, as a fraction of base.")
    damage_growth: float = field()
    max_growth: float = field()
    formation_spacing: float = field(unit="m")
    formation_depth: float = field(unit="m")
    core_guarded_damage: float = field(min=0, max=1, doc="Share of damage a core takes while a tower of its team guards it.")
    core_guard_radius: float = field(unit="m", doc="Towers this close to their core guard it (the two base towers).")
    tower_aggro: float = field(unit="s", doc="How long a tower punishes a champion who hit a champion.")
    champion_bounty: float = field()
    champion_xp: float = field()
    bounty_per_level: float = field()
    streak_bonus: float = field()
    max_streak_bonus: float = field()
    streak_names: list[Localized | None] = field(doc="Announced (with {champion}) at that many kills without dying (index = streak).")
    opening_strike_bonus: float = field()
    respawn_base: float = field(unit="s")
    respawn_per_level: float = field(unit="s")
    respawn_max: float = field(unit="s")
    max_sight: float = field(unit="m", doc="The largest Sight radius; bounds the fog-of-war search.")
    ward_charges: int = field(min=0)
    ward_recharge: float = field(unit="s", doc="Seconds to regain one ward charge.")
    ward_seconds: float = field(unit="s", doc="How long a placed ward lasts.")
    ward_range: float = field(unit="m", doc="How far from the champion a ward can be placed.")
    watchfires: int = field(min=0, doc="Watchfires each champion starts with (no recharge).")
    watchfire_range: float = field(unit="m")
    hushbell_cooldown: float = field(unit="s")
    hushbell_range: float = field(unit="m")
    hushbell_radius: float = field(unit="m")
    hushbell_seconds: float = field(unit="s")
