#!/usr/bin/env python3
"""Generate the API reference (docs/reference/*.md) from the SDK stubs (sdk/**/*.pyi).

One page per module: its docstring, then every public class, function and type alias in
source order, grouped under the stub's own section comments (`# ──── / # Title / # ────`).
Classes list their fields, properties and methods with signatures and docstrings.

    python3 tools/gen_api_docs.py           # write docs/reference/
    python3 tools/gen_api_docs.py --check   # exit 1 if docs/reference/ is stale

The output is deterministic, so --check is an exact comparison. Standard library only.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDK = ROOT / "sdk"
OUT_DIR = ROOT / "docs" / "reference"
MARKER = "<!-- Generated by tools/gen_api_docs.py from sdk/. Do not edit. -->"

COLUMNS = re.compile(r"^\S.*?\S {3,}\S")
SECTION_RULE = re.compile(r"^#\s*[─━-]{8,}\s*$")
CODE_START = re.compile(r"^(@\w|class \w+[:(]|def \w+\(|async def |from [\w.]+ import |import \w+$|await |\w+ = \w+\(|[a-z_]\w*: [A-Z][\w\[\], |]* = )")


# ── Modules ─────────────────────────────────────────────────────────────────────


def module_name(path: Path) -> str:
    rel = path.relative_to(SDK).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def stub_files() -> list[Path]:
    return sorted(SDK.rglob("*.pyi"), key=lambda p: module_name(p))


def page_name(module: str) -> str:
    return f"{module}.md"


# ── Docstrings → Markdown ───────────────────────────────────────────────────────


def escape_prose(line: str) -> str:
    """Escape Markdown/HTML metacharacters outside `code spans`."""
    parts = re.split(r"(`[^`]*`)", line)
    out = []
    for i, part in enumerate(parts):
        if i % 2 == 1:
            out.append(part)
            continue
        part = part.replace("\\", "\\\\").replace("<", "&lt;").replace(">", "&gt;").replace("*", "\\*")
        part = re.sub(r"(?<![\w\\])_(?=\w)|(?<=\w)_(?![\w])", r"\\_", part)  # _leading / trailing_ only
        out.append(part)
    s = "".join(out)
    if re.match(r"^\s*(#|>|[-+] |\d+[.)] |=+\s*$)", s):
        s = "\\" + s.lstrip() if not s.lstrip().startswith("- ") else s
    return s


def fence(lines: list[str], lang: str = "") -> list[str]:
    body = textwrap.dedent("\n".join(lines)).strip("\n").splitlines() if any(l.strip() for l in lines) else []
    ticks = "````" if any(l.lstrip().startswith("```") for l in body) else "```"
    return [f"{ticks}{lang}", *body, ticks]


def doc_md(doc: str | None) -> list[str]:
    """A docstring as Markdown: prose paragraphs, `- ` lists, and indented runs or
    code-looking paragraphs as fenced blocks."""
    if not doc:
        return []
    lines = inspect.cleandoc(doc).splitlines()
    out: list[str] = []
    i = 0
    n = len(lines)

    def indent(s: str) -> int:
        return len(s) - len(s.lstrip())

    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        # A paragraph that is code: a decorator, def, class, import ... at the margin.
        if indent(line) == 0 and CODE_START.match(line):
            block = []
            while i < n and (lines[i].strip() or (i + 1 < n and indent(lines[i + 1]) > 0)):
                block.append(lines[i])
                i += 1
            out += [*fence(block, "python"), ""]
            continue
        # Column-aligned text at the margin (a table written with spaces) is kept verbatim,
        # with the indented lines that continue it.
        if COLUMNS.search(line):
            block = []
            while i < n and lines[i].strip():
                block.append(lines[i])
                i += 1
            out += [*fence(block, "text"), ""]
            continue
        # An indented run (examples, tables, nested lists) is kept verbatim.
        if indent(line) > 0:
            block = []
            while i < n and (not lines[i].strip() or indent(lines[i]) > 0):
                block.append(lines[i])
                i += 1
            while block and not block[-1].strip():
                block.pop()
            items = [b for b in block if b.strip()]
            base = min(indent(b) for b in items)
            if all(b.strip().startswith("- ") or indent(b) > base for b in items) and items[0].strip().startswith("- "):
                cur: list[str] = []
                bullets: list[str] = []
                for b in items:
                    if indent(b) == base:
                        if cur:
                            bullets.append(" ".join(cur))
                        cur = [b.strip()[2:]]
                    else:
                        cur.append(b.strip())
                bullets.append(" ".join(cur))
                out += [f"- {escape_prose(b)}" for b in bullets] + [""]
            else:
                lang = "python" if CODE_START.match(items[0].strip()) else "text"
                out += [*fence(block, lang), ""]
            continue
        # Prose paragraph (up to a blank line or an indented line).
        para = []
        while i < n and lines[i].strip() and indent(lines[i]) == 0:
            if para and (CODE_START.match(lines[i]) or COLUMNS.search(lines[i])):
                break
            para.append(lines[i])
            i += 1
        if para and para[0].startswith("- "):
            for p in para:
                out.append(escape_prose(p) if p.startswith("- ") else "  " + escape_prose(p))
        else:
            out += [escape_prose(p) for p in para]
        out.append("")
    while out and not out[-1]:
        out.pop()
    return out


def indent_block(lines: list[str], prefix: str = "  ") -> list[str]:
    return [prefix + l if l else "" for l in lines]


# ── Signatures ──────────────────────────────────────────────────────────────────


def docstring_of(body: list[ast.stmt]) -> str | None:
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
            and isinstance(body[0].value.value, str):
        return body[0].value.value
    return None


def is_private(name: str) -> bool:
    return name.startswith("_") and not (name.startswith("__") and name.endswith("__"))


_SOURCE = ""  # the module being rendered, for decorators as written


def decorators(node: ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef) -> list[str]:
    return [ast.get_source_segment(_SOURCE, d) or ast.unparse(d) for d in node.decorator_list]


def signature(fn: ast.FunctionDef | ast.AsyncFunctionDef, *, method: bool) -> str:
    args = fn.args
    if method and not any(d in ("staticmethod",) for d in decorators(fn)):
        posonly, regular = list(args.posonlyargs), list(args.args)
        if posonly:
            posonly = posonly[1:]
        elif regular:
            regular = regular[1:]
        args = ast.arguments(posonlyargs=posonly, args=regular, vararg=args.vararg, kwonlyargs=args.kwonlyargs,
                             kw_defaults=args.kw_defaults, kwarg=args.kwarg,
                             defaults=args.defaults[-(len(posonly) + len(regular)):] if (posonly or regular) and args.defaults else [])
    text = format_args(args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns is not None else ""
    prefix = "async def" if isinstance(fn, ast.AsyncFunctionDef) else "def"
    return f"{prefix} {fn.name}({text}){ret}"


def format_args(a: ast.arguments) -> str:
    """Like ast.unparse, but PEP 8 spacing: `x: float = 0`, `n=0`."""
    def one(arg: ast.arg, default: ast.expr | None) -> str:
        s = arg.arg
        if arg.annotation is not None:
            s += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            s += f" = {ast.unparse(default)}" if arg.annotation is not None else f"={ast.unparse(default)}"
        return s

    positional = [*a.posonlyargs, *a.args]
    defaults: list[ast.expr | None] = [None] * (len(positional) - len(a.defaults)) + list(a.defaults)
    parts = [one(arg, d) for arg, d in zip(positional, defaults)]
    if a.posonlyargs:
        parts.insert(len(a.posonlyargs), "/")
    if a.vararg is not None:
        parts.append("*" + one(a.vararg, None))
    elif a.kwonlyargs:
        parts.append("*")
    parts += [one(arg, d) for arg, d in zip(a.kwonlyargs, a.kw_defaults)]
    if a.kwarg is not None:
        parts.append("**" + one(a.kwarg, None))
    return ", ".join(parts)


def wrap_signature(sig: str, width: int = 96) -> str:
    """Break a long signature after its top-level commas."""
    if len(sig) <= width:
        return sig
    open_at = sig.index("(")
    depth = 0
    parts, cur = [], []
    close_at = len(sig)
    for i in range(open_at + 1, len(sig)):
        c = sig[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                close_at = i
                break
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    inner = ",\n".join(f"    {p}" for p in parts)
    return f"{sig[:open_at + 1]}\n{inner},\n{sig[close_at:]}"


def class_header(node: ast.ClassDef) -> str:
    bases = [ast.unparse(b) for b in node.bases] + [ast.unparse(k) for k in node.keywords]
    lines = [f"@{d}" for d in decorators(node)]
    lines.append(f"class {node.name}({', '.join(bases)})" if bases else f"class {node.name}")
    return "\n".join(lines)


# ── Pages ───────────────────────────────────────────────────────────────────────


def sections(src_lines: list[str]) -> list[tuple[int, str]]:
    """(line, title) for each `# ─── / # Title / # ───` banner (1-based line of the title)."""
    out = []
    for i in range(1, len(src_lines) - 1):
        if SECTION_RULE.match(src_lines[i - 1]) and SECTION_RULE.match(src_lines[i + 1]):
            title = src_lines[i].lstrip("#").strip()
            if title:
                out.append((i + 1, title))
    return out


def attr_docs(body: list[ast.stmt]) -> dict[int, str]:
    """Index of statement → the string literal right after it (attribute docstrings)."""
    out = {}
    for i, stmt in enumerate(body[:-1]):
        nxt = body[i + 1]
        if isinstance(stmt, (ast.AnnAssign, ast.Assign)) and isinstance(nxt, ast.Expr) \
                and isinstance(nxt.value, ast.Constant) and isinstance(nxt.value.value, str):
            out[i] = nxt.value.value
    return out


def member_lines(node: ast.ClassDef) -> list[str]:
    out: list[str] = []
    body = node.body
    docs = attr_docs(body)
    fields: list[tuple[str, str | None]] = []
    methods: list[tuple[str, list[str], str | None]] = []  # (name, signatures, doc)
    by_name: dict[str, int] = {}
    dunders: list[str] = []
    for i, stmt in enumerate(body):
        if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            if is_private(stmt.target.id):
                continue
            text = f"{stmt.target.id}: {ast.unparse(stmt.annotation)}"
            if stmt.value is not None:
                text += f" = {ast.unparse(stmt.value)}"
            fields.append((text, docs.get(i)))
        elif isinstance(stmt, ast.Assign) and all(isinstance(t, ast.Name) for t in stmt.targets):
            names = [t.id for t in stmt.targets if not is_private(t.id)]  # type: ignore[attr-defined]
            if names:
                fields.append((f"{' = '.join(names)} = {ast.unparse(stmt.value)}", docs.get(i)))
        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if is_private(stmt.name):
                continue
            if stmt.name.startswith("__") and stmt.name != "__init__":
                if stmt.name not in dunders:
                    dunders.append(stmt.name)
                continue
            decs = decorators(stmt)
            doc = docstring_of(stmt.body)
            if "property" in decs:
                ret = ast.unparse(stmt.returns) if stmt.returns is not None else "Any"
                fields.append((f"{stmt.name}: {ret}  # read-only", doc))
                continue
            if any(d.endswith(".setter") for d in decs):
                continue
            sig = signature(stmt, method=True)
            if "staticmethod" in decs:
                sig = "@staticmethod\n" + sig
            elif "classmethod" in decs:
                sig = "@classmethod\n" + sig
            if stmt.name in by_name:
                name, sigs, prev = methods[by_name[stmt.name]]
                if sig not in sigs:
                    sigs.append(sig)
                methods[by_name[stmt.name]] = (name, sigs, prev or doc)
            else:
                by_name[stmt.name] = len(methods)
                methods.append((stmt.name, [sig], doc))
        elif isinstance(stmt, ast.ClassDef) and not is_private(stmt.name):
            methods.append((stmt.name, [class_header(stmt)], docstring_of(stmt.body)))
    if fields:
        out += ["**Fields**", ""]
        for text, doc in fields:
            out.append(f"- `{text}`")
            d = doc_md(doc)
            if d:
                out += [""] + indent_block(d) + [""]
        out.append("")
    if methods:
        # Signatures in python blocks, each documented one followed by its docs; undocumented
        # neighbours share a block.
        out += ["**Methods**", ""]
        pending: list[str] = []
        for name, sigs, doc in methods:
            sigs = [re.sub(r"^def __init__\((.*)\) -> None$", rf"{node.name}(\1)", s, flags=re.S) for s in sigs]
            mine = [wrap_signature(s) for s in sigs]
            d = doc_md(doc)
            if d:
                if pending:
                    out += [*fence(pending, "python"), ""]
                    pending = []
                out += [*fence(mine, "python"), "", *d, ""]
            else:
                pending += mine
        if pending:
            out += [*fence(pending, "python"), ""]
    if dunders:
        out += ["Also implements " + ", ".join(f"`{d}`" for d in dunders) + ".", ""]
    return out


def is_typevar(stmt: ast.stmt) -> bool:
    return isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call) \
        and isinstance(stmt.value.func, ast.Name) and stmt.value.func.id in ("TypeVar", "ParamSpec", "NewType")


def render_module(path: Path) -> str:
    module = module_name(path)
    global _SOURCE
    src = path.read_text(encoding="utf-8")
    _SOURCE = src
    tree = ast.parse(src)
    src_lines = src.splitlines()
    banners = sections(src_lines)
    body = tree.body
    docs = attr_docs(body)
    rel = path.relative_to(ROOT).as_posix()

    items: list[tuple[int, str, list[str]]] = []  # (line, heading name, lines)
    overloads: dict[str, int] = {}
    for i, stmt in enumerate(body):
        if isinstance(stmt, ast.ClassDef) and not is_private(stmt.name):
            lines = [*fence([class_header(stmt)], "python"), ""]
            d = doc_md(docstring_of(stmt.body))
            if d:
                lines += d + [""]
            lines += member_lines(stmt)
            items.append((stmt.lineno - len(stmt.decorator_list), stmt.name, lines))
        elif isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and not is_private(stmt.name):
            sig = signature(stmt, method=False)
            decs = [d for d in decorators(stmt) if d != "overload"]
            sig = "\n".join([*(f"@{d}" for d in decs), sig])
            doc = doc_md(docstring_of(stmt.body))
            if stmt.name in overloads:
                _, name, lines = items[overloads[stmt.name]]
                # Merge into the first signature block.
                end = lines.index("```", 1)
                lines[end:end] = [wrap_signature(sig)]
                if doc and len(lines) == end + 2:
                    lines += [""] + doc
                continue
            overloads[stmt.name] = len(items)
            lines = fence([wrap_signature(sig)], "python")
            if doc:
                lines += [""] + doc
            items.append((stmt.lineno - len(stmt.decorator_list), f"{stmt.name}()", lines))
        elif isinstance(stmt, (ast.Assign, ast.AnnAssign)) and not is_typevar(stmt):
            if isinstance(stmt, ast.AnnAssign):
                if not isinstance(stmt.target, ast.Name) or is_private(stmt.target.id):
                    continue
                name = stmt.target.id
                text = f"{name}: {ast.unparse(stmt.annotation)}" + (f" = {ast.unparse(stmt.value)}" if stmt.value else "")
            else:
                targets = [t.id for t in stmt.targets if isinstance(t, ast.Name)]
                if not targets or all(is_private(t) for t in targets):
                    continue
                name = targets[0]
                text = f"{' = '.join(targets)} = {ast.unparse(stmt.value)}"
            lines = fence([text], "python")
            d = doc_md(docs.get(i))
            if d:
                lines += [""] + d
            items.append((stmt.lineno, name, lines))

    out = [MARKER, "", f"# `{module}`", ""]
    import_line = "from project import ..." if module == "project" else f"from {module} import ..."
    out += [f"`{import_line}` · source: `{rel}`", ""]
    mod_doc = doc_md(docstring_of(body))
    if mod_doc:
        out += mod_doc + [""]
    if items:
        out += ["## Contents", "", CONTENTS, ""]
    current = None
    for line, name, lines in items:
        title = None
        for bl, bt in banners:
            if bl < line:
                title = bt
        if title is not None and title != current:
            out += [f"## {escape_prose(title)}", ""]
            current = title
        out += [f"### `{name}`", ""]
        out += lines
        while out and not out[-1]:
            out.pop()
        out.append("")
    # Link every item from Contents with the slug GitHub (and github-slugger) gives its heading.
    seen: dict[str, int] = {}
    links = []
    in_fence = False
    for line in out:
        if line.startswith("```"):
            in_fence = not in_fence
        m = None if in_fence else re.match(r"^(#{1,6}) (.+)$", line)
        if m:
            slug = slugify(m[2], seen)
            if m[1] == "###":
                links.append(f"[`{m[2].strip('`')}`](#{slug})")
    tidy: list[str] = []
    in_fence = False
    for line in out:
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and not line and tidy and not tidy[-1]:
            continue
        tidy.append(line)
    text = "\n".join(tidy).rstrip() + "\n"
    return text.replace(CONTENTS, ", ".join(links), 1)


CONTENTS = "<!-- contents -->"


def slugify(heading: str, seen: dict[str, int]) -> str:
    """github-slugger: lowercase, drop punctuation but `-` and `_`, spaces to `-`, dedupe."""
    text = re.sub(r"<[^>]+>", "", heading).replace("\\", "")
    base = re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")
    n = seen.get(base, 0)
    seen[base] = n + 1
    return base if n == 0 else f"{base}-{n}"


def render_index(modules: list[tuple[str, str]]) -> str:
    out = [MARKER, "", "# API reference", "",
           "Generated from the typed stubs in `sdk/` — the public contract of the engine. Game code",
           "imports `parallax` (the core), its plugin modules, and the project's generated `project`",
           "module. A plugin module's names exist in a game only when `Game(plugins=[...])` includes",
           "that plugin (see [`parallax.plugins`](parallax.plugins.md)).", "",
           "Regenerate after changing a stub: `python3 tools/gen_api_docs.py`.", "",
           "| Module | Summary |", "|---|---|"]
    for module, summary in modules:
        out.append(f"| [`{module}`]({page_name(module)}) | {summary.replace('|', '&#124;')} |")
    return "\n".join(out) + "\n"


def first_sentence(doc: str | None) -> str:
    if not doc:
        return ""
    para = inspect.cleandoc(doc).split("\n\n")[0].replace("\n", " ")
    m = re.match(r"(.+?\.)(\s|$)", para)
    s = (m[1] if m else para).strip()
    return escape_prose(s)


def outputs() -> dict[Path, str]:
    files: dict[Path, str] = {}
    modules = []
    for path in stub_files():
        module = module_name(path)
        files[OUT_DIR / page_name(module)] = render_module(path)
        modules.append((module, first_sentence(docstring_of(ast.parse(path.read_text(encoding="utf-8")).body))))
    order = {"parallax": 0, "parallax.plugins": 1, "project": 2, "parallax.test": 3}
    modules.sort(key=lambda m: (order.get(m[0], 9), m[0]))
    files[OUT_DIR / "README.md"] = render_index(modules)
    return files


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/reference/ is stale")
    args = ap.parse_args(argv)
    files = outputs()
    existing = {p for p in OUT_DIR.glob("*.md")
                if p.read_text(encoding="utf-8").startswith(MARKER)} if OUT_DIR.is_dir() else set()
    extra = sorted(existing - set(files))
    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT).as_posix()}", file=sys.stderr)
        for p in extra:
            print(f"no longer generated: {p.relative_to(ROOT).as_posix()}", file=sys.stderr)
        if stale or extra:
            print("run: python3 tools/gen_api_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for p in extra:
        p.unlink()
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} pages to {OUT_DIR.relative_to(ROOT).as_posix()}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
